"""
HTML Table Utility Functions

These utilities parse HTML tables generated by PaddleOCR-VL.

Responsibilities
----------------
- Parse PaddleOCR table HTML.
- Preserve rowspan.
- Preserve colspan.
- Preserve cell order.
- Preserve image references.
- Build a logical rectangular grid.
- Track merged-cell information.

No PaddleOCR inference logic belongs here.
No Excel/OpenPyXL logic belongs here.

The output of this module can be consumed by:
    - Excel exporter
    - CSV exporter
    - API exporter
    - Database exporter
"""

from __future__ import annotations

import itertools
import re

from dataclasses import dataclass, field
from html.parser import HTMLParser
from html import unescape
from pathlib import Path
from typing import Optional


# ============================================================================
# DATA MODELS
# ============================================================================


@dataclass
class TableCell:
    """
    Represents one HTML table cell.

    Parameters
    ----------
    value:
        Text content of the cell.

    row:
        Zero-based logical row.

    column:
        Zero-based logical column.

    rowspan:
        Number of rows occupied by the cell.

    colspan:
        Number of columns occupied by the cell.

    images:
        Image references found inside the cell.

    tag:
        HTML tag: td or th.
    """

    value: str

    row: int
    column: int

    rowspan: int = 1
    colspan: int = 1

    images: list[str] = field(default_factory=list)

    tag: str = "td"

    @property
    def is_merged(self) -> bool:
        """Return True when the cell spans multiple rows or columns."""

        return self.rowspan > 1 or self.colspan > 1

    @property
    def end_row(self) -> int:
        """Return the last logical row occupied by this cell."""

        return self.row + self.rowspan - 1

    @property
    def end_column(self) -> int:
        """Return the last logical column occupied by this cell."""

        return self.column + self.colspan - 1


@dataclass
class StructuredTable:
    """
    Structured representation of a PaddleOCR HTML table.
    """

    cells: list[TableCell] = field(default_factory=list)

    rows: list[list[Optional[TableCell]]] = field(
        default_factory=list
    )

    row_count: int = 0

    column_count: int = 0

    source_html: str = ""

    @property
    def merged_cells(self) -> list[TableCell]:
        """
        Return cells that contain rowspan/colspan.
        """

        return [
            cell
            for cell in self.cells
            if cell.is_merged
        ]

    @property
    def headers(self) -> list[str]:
        """
        Return the first logical row as text.
        """

        if not self.rows:
            return []

        return [
            cell.value if cell else ""
            for cell in self.rows[0]
        ]

    def to_matrix(self) -> list[list[str]]:
        """
        Convert the logical table into a normal text matrix.

        Important:
        This expands merged cells for data-processing purposes.

        It does NOT destroy the original merge information because
        self.cells still contains the rowspan/colspan metadata.
        """

        matrix = []

        for row in self.rows:

            matrix_row = []

            for cell in row:

                if cell is None:
                    matrix_row.append("")
                else:
                    matrix_row.append(cell.value)

            matrix.append(matrix_row)

        return matrix


