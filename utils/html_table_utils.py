class _PaddleTableParser(HTMLParser):
    """
    Internal HTML parser.

    Parses one PaddleOCR-generated HTML table.
    """

    def __init__(self):

        super().__init__(
            convert_charrefs=True
        )

        self.rows: list[list[dict]] = []

        self.current_row: Optional[list[dict]] = None

        self.current_cell: Optional[dict] = None

        self.in_table = False

        self.in_cell = False

        self.in_image = False

        self.text_parts: list[str] = []

    # ------------------------------------------------------------------
    # START TAG
    # ------------------------------------------------------------------

    def handle_starttag(
        self,
        tag: str,
        attrs,
    ):

        tag = tag.lower()

        attributes = {
            key.lower(): value
            for key, value in attrs
        }

        # --------------------------------------------------------------
        # TABLE
        # --------------------------------------------------------------

        if tag == "table":

            self.in_table = True

            return

        # --------------------------------------------------------------
        # ROW
        # --------------------------------------------------------------

        if tag == "tr":

            if self.current_row is not None:
                self._finish_row()

            self.current_row = []

            return

        # --------------------------------------------------------------
        # CELL
        # --------------------------------------------------------------

        if tag in {"td", "th"}:

            if self.current_row is None:
                self.current_row = []

            self.current_cell = {
                "tag": tag,
                "rowspan": self._safe_int(
                    attributes.get("rowspan"),
                    default=1,
                ),
                "colspan": self._safe_int(
                    attributes.get("colspan"),
                    default=1,
                ),
                "text_parts": [],
                "images": [],
            }

            self.text_parts = []

            self.in_cell = True

            return

        # --------------------------------------------------------------
        # IMAGE
        # --------------------------------------------------------------

        if tag == "img" and self.in_cell:

            src = (
                attributes.get("src")
                or attributes.get("data-src")
                or ""
            )

            if src:

                self.current_cell[
                    "images"
                ].append(src)

            self.in_image = True

            return

        # --------------------------------------------------------------
        # BR
        # --------------------------------------------------------------

        if tag == "br" and self.in_cell:

            self.text_parts.append("\n")

    # ------------------------------------------------------------------
    # END TAG
    # ------------------------------------------------------------------

    def handle_endtag(
        self,
        tag: str,
    ):

        tag = tag.lower()

        # --------------------------------------------------------------
        # CELL
        # --------------------------------------------------------------

        if tag in {"td", "th"}:

            self._finish_cell()

            return

        # --------------------------------------------------------------
        # ROW
        # --------------------------------------------------------------

        if tag == "tr":

            self._finish_row()

            return

        # --------------------------------------------------------------
        # TABLE
        # --------------------------------------------------------------

        if tag == "table":

            if self.current_row is not None:

                self._finish_row()

            self.in_table = False

    # ------------------------------------------------------------------
    # TEXT
    # ------------------------------------------------------------------

    def handle_data(
        self,
        data: str,
    ):

        if not self.in_cell:
            return

        if not data:
            return

        self.text_parts.append(data)

    # ------------------------------------------------------------------
    # CELL FINISH
    # ------------------------------------------------------------------

    def _finish_cell(self):

        if not self.current_cell:
            return

        text = "".join(
            self.text_parts
        )

        text = self._clean_text(text)

        self.current_cell[
            "text"
        ] = text

        self.current_cell[
            "images"
        ] = list(
            self.current_cell.get(
                "images",
                [],
            )
        )

        if self.current_row is None:

            self.current_row = []

        self.current_row.append(
            self.current_cell
        )

        self.current_cell = None

        self.text_parts = []

        self.in_cell = False

        self.in_image = False

    # ------------------------------------------------------------------
    # ROW FINISH
    # ------------------------------------------------------------------

    def _finish_row(self):

        if self.current_cell is not None:

            self._finish_cell()

        if self.current_row:

            self.rows.append(
                self.current_row
            )

        self.current_row = None

    # ------------------------------------------------------------------
    # HELPERS
    # ------------------------------------------------------------------

    @staticmethod
    def _safe_int(
        value,
        default: int = 1,
    ) -> int:

        try:

            parsed = int(
                str(value).strip()
            )

            return max(
                parsed,
                1,
            )

        except (
            TypeError,
            ValueError,
        ):

            return default

    @staticmethod
    def _clean_text(
        text: str,
    ) -> str:

        text = unescape(text)

        # Normalize whitespace while preserving
        # intentional line breaks.
        lines = []

        for line in text.splitlines():

            cleaned = " ".join(
                line.split()
            )

            if cleaned:
                lines.append(cleaned)

        return "\n".join(lines)


