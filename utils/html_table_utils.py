def _build_structured_table(
    raw_rows: list[list[dict]],
    source_html: str,
) -> StructuredTable:
    """
    Convert raw HTML rows into a logical grid.

    This is the important part.

    It understands rowspan and colspan.

    Example:

        <td rowspan="3">$1.65</td>

    occupies:

        row 5
        row 6
        row 7

    Example:

        <td colspan="11">FRESH</td>

    occupies:

        columns 1 -> 11
    """

    table = StructuredTable(
        source_html=source_html
    )

    # grid[row][column] = TableCell
    grid: list[list[Optional[TableCell]]] = []

    def ensure_row(
        row_index: int,
    ):

        while len(grid) <= row_index:

            grid.append([])

    def ensure_column(
        row_index: int,
        column_index: int,
    ):

        ensure_row(row_index)

        while (
            len(grid[row_index])
            <= column_index
        ):

            grid[row_index].append(None)

    def find_next_free_column(
        row_index: int,
        start_column: int,
    ) -> int:

        ensure_row(row_index)

        column = start_column

        while True:

            ensure_column(
                row_index,
                column,
            )

            if grid[row_index][column] is None:
                return column

            column += 1

    # --------------------------------------------------------------
    # Process every HTML row
    # --------------------------------------------------------------

    for html_row_index, raw_cells in enumerate(
        raw_rows
    ):

        ensure_row(
            html_row_index
        )

        current_column = 0

        for raw_cell in raw_cells:

            # Find first available logical column.
            current_column = find_next_free_column(
                html_row_index,
                current_column,
            )

            rowspan = max(
                int(
                    raw_cell.get(
                        "rowspan",
                        1,
                    )
                ),
                1,
            )

            colspan = max(
                int(
                    raw_cell.get(
                        "colspan",
                        1,
                    )
                ),
                1,
            )

            cell = TableCell(
                value=raw_cell.get(
                    "text",
                    "",
                ),
                row=html_row_index,
                column=current_column,
                rowspan=rowspan,
                colspan=colspan,
                images=list(
                    raw_cell.get(
                        "images",
                        [],
                    )
                ),
                tag=raw_cell.get(
                    "tag",
                    "td",
                ),
            )

            table.cells.append(
                cell
            )

            # ------------------------------------------------------
            # Occupy every logical position
            # ------------------------------------------------------

            for row_offset in range(
                rowspan
            ):

                logical_row = (
                    html_row_index
                    + row_offset
                )

                ensure_row(
                    logical_row
                )

                for column_offset in range(
                    colspan
                ):

                    logical_column = (
                        current_column
                        + column_offset
                    )

                    ensure_column(
                        logical_row,
                        logical_column,
                    )

                    existing = grid[
                        logical_row
                    ][
                        logical_column
                    ]

                    if existing is not None:

                        raise ValueError(
                            "Invalid HTML table structure: "
                            f"cell overlap at "
                            f"row={logical_row}, "
                            f"column={logical_column}."
                        )

                    grid[
                        logical_row
                    ][
                        logical_column
                    ] = cell

            current_column += colspan

    # --------------------------------------------------------------
    # Normalize column widths
    # --------------------------------------------------------------

    column_count = max(
        (
            len(row)
            for row in grid
        ),
        default=0,
    )

    for row in grid:

        while len(row) < column_count:

            row.append(None)

    table.rows = grid

    table.row_count = len(grid)

    table.column_count = column_count

    return table


