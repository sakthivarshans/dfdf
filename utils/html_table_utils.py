def parse_html_table(
    html: str,
) -> StructuredTable:
    """
    Parse one PaddleOCR HTML table.

    Parameters
    ----------
    html:
        HTML returned in PaddleOCR's block_content.

    Returns
    -------
    StructuredTable
    """

    if not html or not html.strip():

        raise ValueError(
            "HTML table content is empty."
        )

    parser = _PaddleTableParser()

    parser.feed(html)

    parser.close()

    if not parser.rows:

        raise ValueError(
            "No table rows found in HTML."
        )

    rows = _repair_missing_image_cells(
        parser.rows
    )

    return _build_structured_table(
        rows,
        html,
    )


# ============================================================================
# MISSING IMAGE CELL REPAIR
#
# PaddleOCR-VL sometimes omits the leading "Image" <td> entirely for a
# row instead of emitting an empty one (which is what happens for a
# normal continuation row inside a rowspan group). When that happens,
# every later cell in that specific <tr> lands one logical column to
# the left of where it belongs, and downstream code (which always
# strips column 0 as "the Image column") ends up discarding the real
# Product Description text instead of an empty placeholder.
#
# This step detects that pattern per-row, before the logical grid is
# built, and repairs it by inserting a synthetic empty Image cell (or,
# when the Image and Product Description got merged into one <td>,
# by splitting that single cell back into Image / Product Description
# / Case Size).
# ============================================================================


_IMAGE_PLACEHOLDER_RE = re.compile(
    r"^\d{1,4}(\s*\[\w+\])?$|^\[\w+\]$"
)

_TRAILING_CASE_SIZE_RE = re.compile(
    r"^(.*\S)\s+(\d+\s*[xX]\s*\d+(?:\.\d+)?\s*(?:CL|ML|G|KG|LTR|L)\b)\s*$",
    re.IGNORECASE,
)


def _normalize_cell_text(cell: dict) -> str:

    text = cell.get("text", "") or ""

    # PaddleOCR-VL sometimes emits a literal two-character "\n"
    # escape sequence inside cell text (e.g. "80\n" as the four
    # characters 8, 0, backslash, n) instead of a real line break,
    # most often right before an <img> tag in the Image/EAN columns.
    # Treat it the same as real whitespace.
    text = text.replace("\\n", " ")

    return " ".join(text.split())


def _new_cell(
    text: str = "",
    images: Optional[list[str]] = None,
) -> dict:

    return {
        "tag": "td",
        "rowspan": 1,
        "colspan": 1,
        "text": text,
        "images": list(images or []),
    }


def _looks_like_image_column_value(cell: dict) -> bool:
    """
    Return True when a cell's content is plausible content for the
    leading "Image" column: a product/group number, a footnote tag
    such as "[F01]", an actual image, or nothing at all.
    """

    text = _normalize_cell_text(cell)

    if not text:
        return True

    if _IMAGE_PLACEHOLDER_RE.match(text):
        return True

    # An image with no accompanying free text is a normal Image cell
    # (e.g. a photo with no overlaid product number).
    if cell.get("images") and not any(
        char.isalpha() for char in text
    ):
        return True

    return False


def _repair_missing_image_cells(
    raw_rows: list[list[dict]],
) -> list[list[dict]]:
    """
    Repair rows whose leading "Image" cell was dropped entirely by
    PaddleOCR-VL instead of being emitted empty.

    Only applies to tables whose header row starts with an "Image"
    column, and never touches the header row itself.

    Two kinds of rows must NOT be touched even though their first
    cell is not itself image-like:

    - Section-banner rows such as ``<td colspan="11">FRESH</td>``,
      which are a single cell spanning the whole table width.
    - Continuation rows that sit underneath a real ``rowspan`` on a
      previous row's Image cell (e.g. a shared group number/footnote
      block). For those rows, column 0 is legitimately already
      occupied by the row above, exactly like a "Consumer Deal"
      rowspan group, so the row's own first cell is correctly its
      Product Description (or per-row photo), not a dropped cell.
    """

    if len(raw_rows) < 2:
        return raw_rows

    header_row = raw_rows[0]

    if not header_row:
        return raw_rows

    header_text = _normalize_cell_text(
        header_row[0]
    ).strip().lower()

    if header_text != "image":
        return raw_rows

    repaired_rows = [header_row]

    image_rowspan_remaining = 0

    for row in raw_rows[1:]:

        if not row:
            repaired_rows.append(row)
            continue

        # ------------------------------------------------------------
        # Section-banner row (one cell spanning the whole table).
        # ------------------------------------------------------------

        if len(row) == 1 and row[0].get("colspan", 1) > 1:
            repaired_rows.append(row)
            continue

        # ------------------------------------------------------------
        # Continuation row already covered by a previous row's Image
        # rowspan: its first cell is genuinely not an Image value.
        # ------------------------------------------------------------

        if image_rowspan_remaining > 0:
            image_rowspan_remaining -= 1
            repaired_rows.append(row)
            continue

        first_cell = row[0]

        image_rowspan_remaining = max(
            int(first_cell.get("rowspan", 1)) - 1,
            0,
        )

        if _looks_like_image_column_value(first_cell):
            repaired_rows.append(row)
            continue

        text = _normalize_cell_text(first_cell)

        if not any(char.isalpha() for char in text):
            # Doesn't look like a product description either;
            # leave it alone rather than guessing.
            repaired_rows.append(row)
            continue

        if not first_cell.get("images"):

            # The leading <td> was skipped entirely and this cell is
            # really the Product Description. Give it back an empty
            # Image placeholder.
            repaired_rows.append(
                _drop_duplicate_price_before_percentage(
                    [_new_cell()] + row
                )
            )
            continue

        # The Image and Product Description (and possibly Case Size)
        # were merged into a single <td>. Split them back apart.
        match = _TRAILING_CASE_SIZE_RE.match(text)

        if match:
            description_text, case_size_text = match.groups()
        else:
            description_text, case_size_text = text, ""

        replacement = [
            _new_cell(images=first_cell.get("images")),
            _new_cell(text=description_text),
        ]

        if case_size_text:
            replacement.append(
                _new_cell(text=case_size_text)
            )

        repaired_rows.append(
            _drop_duplicate_price_before_percentage(
                replacement + _merge_leading_orphan_digit_image(row[1:])
            )
        )

    return repaired_rows


def _merge_leading_orphan_digit_image(
    tail: list[dict],
) -> list[dict]:
    """
    Merge a bare digit cell immediately followed by a bare image cell,
    near the start of ``tail``, into one cell.

    Scoped narrowly to the cells right after a Product Description /
    Image split repair: on a row already known to be malformed, the
    EAN Barcode column (normally one cell such as
    ``<td>7<img .../></td>``) is sometimes split into two separate
    <td> elements, which would otherwise desynchronize every column
    after it (Prom WSP, Std RSP, Promo POR, ...). Only the first few
    cells are examined (Case Size / Midas Code / EAN Barcode)
    to avoid ever touching the price columns further right.
    """

    search_limit = min(len(tail) - 1, 3)

    for index in range(search_limit):

        first, second = tail[index], tail[index + 1]

        if first.get("images"):
            continue

        if not re.fullmatch(r"\d{1,2}", _normalize_cell_text(first)):
            continue

        if not second.get("images") or _normalize_cell_text(second):
            continue

        merged = _new_cell(
            text=_normalize_cell_text(first),
            images=second.get("images"),
        )

        return tail[:index] + [merged] + tail[index + 2 :]

    return tail


_PRICE_RE = re.compile(r"^[£$€]\d+(\.\d{2})?$")

_PERCENTAGE_RE = re.compile(r"^\d+(\.\d+)?%$")


def _drop_duplicate_price_before_percentage(
    row: list[dict],
) -> list[dict]:
    """
    Drop a stray duplicate price cell that PaddleOCR-VL sometimes
    hallucinates right after the real "Std RSP" value on a row that
    belongs to a "Consumer Deal" rowspan group.

    Pattern observed in the wild:

        ... Prom WSP | Std RSP | <duplicate of Std RSP> | Promo POR ...

    The duplicate cell does not correspond to anything printed on the
    page; the row's real Consumer Deal value is the merged rowspan
    cell inherited from the top of its group. Left in place, the
    duplicate shifts every following column (Promo POR, Leaflet, ...)
    one position to the right.
    """

    for index in range(len(row) - 2):

        current_text = _normalize_cell_text(row[index])
        next_text = _normalize_cell_text(row[index + 1])
        following_text = _normalize_cell_text(row[index + 2])

        if not current_text or current_text != next_text:
            continue

        if not _PRICE_RE.match(current_text):
            continue

        if row[index].get("images") or row[index + 1].get("images"):
            continue

        if not _PERCENTAGE_RE.match(following_text):
            continue

        return row[: index + 1] + row[index + 2 :]

    return row


